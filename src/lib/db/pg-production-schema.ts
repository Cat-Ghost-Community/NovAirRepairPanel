import model from './pg-production-schema.json';

/** Frozen canonical schema, not an introspection/import operation. Changing a
 * deployed baseline requires a new migration, never editing the applied file. */
export const POSTGRES_BASELINE=model;
export function productionNamespace(schema:string){
 if(schema!=='repaid'&&!/^repaid_integration_[a-f0-9]{24}$/.test(schema))throw Error('Explicit production or isolated application schema required');
 return '"'+schema+'"';
}
const identifier=(name:string)=>{if(!/^[a-z_][a-z_0-9]*$/.test(name))throw Error('Invalid frozen schema identifier');return '"'+name+'"';};
export const FOUNDATION_WRITABLE_TABLES=[
 'branches','users','user_permissions','sessions','login_attempts','settings','counters',
 'customers','customer_events','audit_logs','operation_receipts',
 'accounting_accounts','accounting_periods','accounting_journals','accounting_lines',
 'accounting_cutover','accounting_events','accounting_event_reviews','accounting_journal_voids',
] as const;

function checkExpression(expression:string,schema:string){
 if(expression.includes('json_valid(member_ids)'))return `${schema}.repaid_json_array_bounded(member_ids)`;
 const result=expression.replace(/typeof\(([a-z_]+)\)='integer'/g,'TRUE');
 if(/\b(?:typeof|json_valid|json_type|json_array_length)\s*\(/.test(result))throw Error('Unreviewed SQLite CHECK cannot become PostgreSQL');
 return result;
}
function qualifyRelations(sql:string,schema:string){
 const known=new Set([...model.tables,...model.views].map(t=>t.name));
 return sql.replace(/'(?:''|[^'])*'|"(?:""|[^"])*"|\b[a-z_][a-z_0-9]*\b/gi,token=>{
  if(token.startsWith("'"))return token;
  const name=token.startsWith('"')?token.slice(1,-1):token;
  return known.has(name)?schema+'.'+identifier(name):token;
 });
}

export function postgresBaselineStatements(namespace:string){
 const schema=productionNamespace(namespace),table=(name:string)=>schema+'.'+identifier(name),statements:string[]=[];
 statements.push(`CREATE FUNCTION ${schema}.repaid_json_array_bounded(value text) RETURNS boolean LANGUAGE plpgsql IMMUTABLE SET search_path=pg_catalog AS $fn$ BEGIN RETURN jsonb_typeof(value::jsonb)='array' AND jsonb_array_length(value::jsonb) BETWEEN 1 AND 100; EXCEPTION WHEN invalid_text_representation OR invalid_parameter_value THEN RETURN false; END $fn$`);
 for(const entity of model.tables){
  const primary=entity.columns.filter(c=>c.primary).sort((a,b)=>a.primary-b.primary),identity=primary.length===1&&primary[0].type==='bigint'?primary[0].name:null;
  const definitions=entity.columns.map(column=>{
   const type=column.type==='text'?'text COLLATE "C"':column.type;
   const generated=identity===column.name?' GENERATED BY DEFAULT AS IDENTITY':'';
   const fallback=column.default==null?'':column.default==="datetime('now')"?' DEFAULT '+`to_char(clock_timestamp() AT TIME ZONE 'UTC','YYYY-MM-DD"T"HH24:MI:SS.MS"Z"')`:' DEFAULT '+column.default;
   return identifier(column.name)+' '+type+generated+(column.required?' NOT NULL':'')+(generated?'':fallback);
  });
  definitions.push('PRIMARY KEY ('+primary.map(c=>identifier(c.name)).join(',')+')');
  entity.unique.forEach((columns,i)=>definitions.push(`CONSTRAINT ${identifier('base_'+entity.name+'_u_'+i)} UNIQUE (${columns.map(identifier).join(',')})`));
  entity.checks.forEach((check,i)=>definitions.push(`CONSTRAINT ${identifier('base_'+entity.name+'_c_'+i)} CHECK (${checkExpression(check,schema)})`));
  statements.push(`CREATE TABLE ${table(entity.name)} (${definitions.join(',')})`);
 }
 for(const entity of model.tables)entity.foreignKeys.forEach((foreign,i)=>statements.push(`ALTER TABLE ${table(entity.name)} ADD CONSTRAINT ${identifier('base_fk_'+i)} FOREIGN KEY (${identifier(foreign.column)}) REFERENCES ${table(foreign.table)}(${identifier(foreign.target)}) ON UPDATE ${foreign.onUpdate} ON DELETE ${foreign.onDelete} DEFERRABLE INITIALLY IMMEDIATE`));
 // Missing legacy declarations are strengthened for the migrated customer slice.
 // Any future populated cutover must review orphan evidence instead of deleting it.
 for(const [name,column,parent] of [
  ['customers','branch_id','branches'],['customers','created_by','users'],
  ['customer_events','customer_id','customers'],['customer_events','user_id','users'],
  ['audit_logs','user_id','users'],['audit_logs','branch_id','branches'],
 ] as const)statements.push(`ALTER TABLE ${table(name)} ADD CONSTRAINT ${identifier('foundation_fk_'+column)} FOREIGN KEY (${identifier(column)}) REFERENCES ${table(parent)}(id) DEFERRABLE INITIALLY IMMEDIATE`);
 for(const index of model.indexes){
  const prefix=/^CREATE\s+(UNIQUE\s+)?INDEX\s+(?:IF\s+NOT\s+EXISTS\s+)?[^\s]+\s+ON\s+[^\s(]+\s*/i.exec(index.sql);
  if(!prefix)throw Error('Unrecognized frozen index definition');
  statements.push(`CREATE ${prefix[1]?'UNIQUE ':''}INDEX ${identifier(index.name)} ON ${table(index.table)} ${index.sql.slice(prefix[0].length)}`);
 }
 const remaining=[...model.views],created=new Set<string>();
 while(remaining.length){
  const index=remaining.findIndex(view=>model.views.every(dependency=>dependency.name===view.name||!new RegExp('\\b'+dependency.name+'\\b').test(view.sql)||created.has(dependency.name)));
  if(index<0)throw Error('Frozen read model dependency cycle');
  const [view]=remaining.splice(index,1),body=view.sql.replace(/^CREATE\s+VIEW\s+\w+\s+AS\s+/i,'').replace(/MAX\(0,/g,'GREATEST(0,').replace(/date\('now'\)/g,"to_char(clock_timestamp() AT TIME ZONE 'UTC','YYYY-MM-DD')");
  statements.push(`CREATE VIEW ${table(view.name)} AS ${qualifyRelations(body,schema)}`);created.add(view.name);
 }
 return statements;
}

/** Unported modules cannot weaken source invariants through direct target DML.
 * A future reviewed migration must replace each fence with native guard parity. */
export function postgresFoundationFenceStatements(namespace:string){
 const schema=productionNamespace(namespace),writable=new Set<string>(FOUNDATION_WRITABLE_TABLES);
 const statements=[`CREATE FUNCTION ${schema}.repaid_unported_write_fence() RETURNS trigger LANGUAGE plpgsql SET search_path=pg_catalog AS $fn$ BEGIN RAISE EXCEPTION 'Domain is not enabled for PostgreSQL writes until native invariant parity is accepted' USING ERRCODE='55000'; END $fn$`];
 for(const entity of model.tables)if(!writable.has(entity.name))statements.push(`CREATE TRIGGER repaid_unported_write BEFORE INSERT OR UPDATE OR DELETE OR TRUNCATE ON ${schema}.${identifier(entity.name)} FOR EACH STATEMENT EXECUTE FUNCTION ${schema}.repaid_unported_write_fence()`);
 statements.push(`CREATE FUNCTION ${schema}.repaid_customer_branch_guard() RETURNS trigger LANGUAGE plpgsql SET search_path=pg_catalog AS $fn$ BEGIN IF NEW.branch_id IS DISTINCT FROM OLD.branch_id THEN RAISE EXCEPTION 'Customer financial branch ownership requires a reviewed transfer' USING ERRCODE='23514'; END IF; RETURN NEW; END $fn$`);
 statements.push(`CREATE TRIGGER repaid_customer_branch BEFORE UPDATE ON ${schema}.customers FOR EACH ROW EXECUTE FUNCTION ${schema}.repaid_customer_branch_guard()`);
 statements.push(`CREATE FUNCTION ${schema}.repaid_audit_immutable() RETURNS trigger LANGUAGE plpgsql SET search_path=pg_catalog AS $fn$ BEGIN RAISE EXCEPTION 'Audit history is immutable' USING ERRCODE='23514'; END $fn$`);
 for(const name of ['audit_logs','customer_events'])statements.push(`CREATE TRIGGER repaid_history_immutable BEFORE UPDATE OR DELETE OR TRUNCATE ON ${schema}.${identifier(name)} FOR EACH STATEMENT EXECUTE FUNCTION ${schema}.repaid_audit_immutable()`);
 return statements;
}
export function productionSchemaCoverage(){
 const writable=new Set<string>(FOUNDATION_WRITABLE_TABLES);
 return {baseline_tables:model.tables.length,baseline_indexes:model.indexes.length,read_views:model.views.length,source_schema_sha256:model.sourceSchemaSha256,
  enabled_foundation_tables:[...FOUNDATION_WRITABLE_TABLES],fenced_tables:model.tables.filter(t=>!writable.has(t.name)).map(t=>t.name),sqlite_trigger_inventory:model.sqliteTriggerInventory,
  native_guard_families:['ledger','durable_operations'],bank_native_production_parity:false,application_wide_ready:false};
}
