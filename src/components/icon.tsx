export type IconName = keyof typeof MAP | string;

/** آیکون خطی SVG — یکدست با تم (رنگ از currentColor) */
export function Icon({ name, size = 16, className, strokeWidth = 2 }: {
  name: IconName;
  size?: number;
  className?: string;
  strokeWidth?: number;
}) {
  const Cmp = MAP[name] ?? CircleDot;
  return <Cmp size={size} className={className} strokeWidth={strokeWidth} aria-hidden="true" />;
}

/** آیکون درون دکمه/لینک با فاصله استاندارد از متن */
export function IconBtn({ name, size = 14, children, className }: { name: IconName; size?: number; children: React.ReactNode; className?: string }) {
  return (
    <span className={`inline-flex items-center gap-1.5 ${className ?? ""}`}>
      <Icon name={name} size={size} />
      {children}
    </span>
  );
}
